// Helper functions to mock data
const inDays = (days: number, hours: number = 9): Date => {
  const date = new Date();
  date.setDate(date.getDate() + days);
  date.setHours(hours, 0, 0, 0);

  return date;
};

const ago = (days: number): Date => inDays(-days);

